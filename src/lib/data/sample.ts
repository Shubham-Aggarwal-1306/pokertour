const slugify = (s: string) =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

export function buildSampleTournaments(now = new Date()): Tournament[] {
  const day = 86_400_000;
  const midnight = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  return SAMPLES.map(({ startInDays, durationDays, startHourUtc, ...t }) => {
    const start = new Date(midnight + startInDays * day + startHourUtc * 3_600_000);
    const end = new Date(start.getTime() + (durationDays - 1) * day);
    return {
      ...t,
      id: `sample-${slugify(t.name)}`,
      startDate: start.toISOString(),
      endDate: durationDays > 1 ? end.toISOString() : null,
      buyInUsd: toUsd(t.buyIn, t.currency),
      source: "sample",
      sourceUrl: null,
      updatedAt: now.toISOString(),
    };
  });
}
